export const getServiceBySlug = (slug) => {
  if (!slug) return null;
  const cleanSlug = slug.toLowerCase().trim();
  return (
    services.find(
      (s) =>
        s.slug === cleanSlug ||
        s.id === cleanSlug ||
        (s.aliases && s.aliases.includes(cleanSlug))
    ) || null
  );
};
